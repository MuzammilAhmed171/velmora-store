#!/usr/bin/env node
// Velmora interactive setup — asks a few simple questions and writes your .env files.
// Run with: npm run setup
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const readline = require("readline");
const { execSync, spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const SERVER_ENV = path.join(ROOT, "server", ".env");
const CLIENT_ENV = path.join(ROOT, "client", ".env");

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise((resolve) => rl.question(q, (a) => resolve(a.trim())));

function log(msg) { console.log(msg); }
function ok(msg) { console.log("  [OK] " + msg); }
function bad(msg) { console.log("  [!!] " + msg); }

function ensureServerDeps() {
  const nm = path.join(ROOT, "server", "node_modules");
  if (fs.existsSync(nm)) { ok("Server files already installed."); return; }
  log("\nInstalling server files (one-time, takes 1-3 minutes)...");
  execSync("npm install --no-audit --no-fund", { cwd: path.join(ROOT, "server"), stdio: "inherit" });
  ok("Server files installed.");
}

async function testMongo(uri) {
  let mongoose;
  try {
    mongoose = require(path.join(ROOT, "server", "node_modules", "mongoose"));
  } catch {
    return { ok: false, error: "mongoose not found (run npm install in server/)" };
  }
  try {
    await mongoose.connect(uri, { serverSelectionTimeoutMS: 10000 });
    const dbs = await mongoose.connection.db.admin().listDatabases().catch(() => null);
    await mongoose.disconnect();
    return { ok: true, dbs: dbs ? dbs.databases.length : null };
  } catch (e) {
    return { ok: false, error: e.message.split("\n")[0] };
  }
}

function writeEnv(file, lines) {
  const content = "# Generated by `npm run setup` on " + new Date().toISOString() + "\n" + lines.join("\n") + "\n";
  fs.writeFileSync(file, content);
}

async function main() {
  log("\n==============================================");
  log("  VELMORA — easy setup");
  log("==============================================");
  log("This will ask you 3 quick questions and set up");
  log("everything automatically. It takes ~2 minutes.\n");

  ensureServerDeps();

  // Q1: MongoDB connection string
  let uri = "";
  for (let attempt = 0; attempt < 3; attempt++) {
    uri = await ask("Q1/3  Paste your MongoDB connection string\n      (starts with mongodb+srv:// ...):\n> ");
    if (!/^mongodb(\+srv)?:\/\//.test(uri)) {
      bad("That doesn't look like a MongoDB connection string. It should start with mongodb+srv://");
      continue;
    }
    log("\nTesting the connection...");
    const res = await testMongo(uri);
    if (res.ok) { ok("Connected to MongoDB successfully!"); break; }
    bad("Could not connect: " + res.error);
    log("      Tip: check the TROUBLESHOOTING section in README.md (IP whitelist 0.0.0.0/0).");
    uri = "";
  }
  if (!uri) { bad("Setup stopped: no working MongoDB connection string."); rl.close(); process.exit(1); }

  // Q2: secret
  const secret = await ask("\nQ2/3  Secret key for logins (press ENTER to auto-generate):\n> ");
  const tokenSecret = secret || crypto.randomBytes(32).toString("hex");
  ok("Secret key ready.");

  // Q3: stripe (optional)
  const stripe = await ask("\nQ3/3  Stripe test key (optional, press ENTER to skip — you can add it later):\n> ");
  if (stripe) ok("Stripe key saved (test mode).");
  else log("      Skipped — card payments stay in demo mode until you add a key.");

  // Write env files
  writeEnv(SERVER_ENV, [
    "MONGODB_URI=" + uri,
    "TOKEN_SECRET=" + tokenSecret,
    "PORT=4000",
    "FRONTEND_URL=http://localhost:5173",
    stripe ? "STRIPE_SECRET_KEY=" + stripe : "# STRIPE_SECRET_KEY=sk_test_...  (paste your Stripe test key here later)",
  ]);
  writeEnv(CLIENT_ENV, ["VITE_API_URL=http://localhost:4000"]);
  ok("Config files written (server/.env and client/.env).");

  // Seed
  const seedAns = await ask("\nLoad the demo store data (157 products, coupons, etc.)? [Y/n]:\n> ");
  if (!/^n/i.test(seedAns)) {
    log("\nLoading demo data...");
    const r = spawnSync("npm", ["run", "db:seed"], { cwd: path.join(ROOT, "server"), stdio: "inherit", shell: true });
    if (r.status === 0) ok("Demo data loaded.");
    else bad("Seeding had an issue — you can retry later with: npm run db:seed --prefix server");
  }

  log("\n==============================================");
  log("  SETUP COMPLETE");
  log("==============================================");
  log("Start your store with:");
  log("    npm run dev");
  log("Then open the web address it prints (usually http://localhost:5173).");
  log("\nAdmin login: admin@velmora.pk  /  Admin123!");
  log("==============================================\n");
  rl.close();
}

main().catch((e) => { console.error(e); rl.close(); process.exit(1); });
